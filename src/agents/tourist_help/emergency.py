"""
Tourist Help Emergency Assistance Node (Story 2.2)
Queries the existing EmergencyDB via answer_emergency_query() and prepares
a verified candidate response for the verification node.
Module: src/agents/tourist_help/emergency.py
"""

import logging
from typing import Any, Dict

logger = logging.getLogger(__name__)


def _get_latest_user_query(state: Dict[str, Any]) -> str:
    """Extract the most recent human message from state."""
    q = state.get("user_query", "")
    if q:
        return q
    messages = state.get("messages", [])
    for msg in reversed(messages):
        if hasattr(msg, "type") and msg.type == "human":
            return str(msg.content).strip()
        if isinstance(msg, tuple) and len(msg) >= 2 and str(msg[0]).lower() in {"human", "user"}:
            return str(msg[1]).strip()
    return ""


def emergency_rag_node(state: Dict[str, Any]) -> Dict[str, Any]:
    """
    LangGraph node: queries the verified emergency registry via answer_emergency_query()
    from the existing RAG pipeline. Emergency numbers are NEVER generated by an LLM —
    they are picked from the registry-verified knowledge base CSV.

    Passes output to the Help Verification Guardrail Node.
    """
    # Import from the actual module path (src.rag.tourist_rag)
    try:
        from src.rag.tourist_rag.answer import answer_emergency_query
    except ImportError:
        from src.rag.answer import answer_emergency_query  # type: ignore

    # Sanitize location: "Location unavailable" must not leak into the answer header
    location = state.get("current_location") or ""
    if location == "Location unavailable" or not location:
        location = None

    user_query = _get_latest_user_query(state)
    if not user_query:
        user_query = "emergency help Egypt"

    logger.debug("[EmergencyRAG] query=%r location=%r", user_query, location)

    try:
        result = answer_emergency_query(query=user_query, location=location)
    except Exception as exc:
        logger.error("[EmergencyRAG] answer_emergency_query failed: %s", exc)
        from src.agents.tourist_help.prompts import DEFAULT_EMERGENCY_FALLBACK
        return {
            "retrieved_context": "",
            "candidate_response": DEFAULT_EMERGENCY_FALLBACK,
            "response": DEFAULT_EMERGENCY_FALLBACK,
            "retrieval_sources": [],
            "rag_status": "error",
            "out_of_scope": False,
            "help_domain": "emergency",
            "current_intent": "emergency",
            "next_agent": "emergency_completed",
        }

    logger.debug("[EmergencyRAG] answered. context_len=%d", len(result.context))
    return {
        "retrieved_context": result.context,
        "candidate_response": result.answer,
        "response": result.answer,
        "retrieval_sources": result.sources,
        "rag_status": result.status,
        "out_of_scope": False,
        "help_domain": "emergency",
        "current_intent": "emergency",
        "next_agent": "emergency_completed",
    }


# Backward-compatible alias
emergency_agent_node = emergency_rag_node
