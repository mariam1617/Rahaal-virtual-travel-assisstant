"""
Tourist Help Verification Schemas & Data Contracts 
Defines Pydantic models for structured verification outputs and RAG guardrail evaluation.
"""

from typing import List, Optional, Literal
from pydantic import BaseModel, Field

HelpDomain = Literal["emergency", "advisories", "visa", "transit", "general"]


class RAGInputContext(BaseModel):
    """
    Data contract representing the payload delivered from the RAG retrieval/generation
    nodes to the Help Verification Guardrail node.
    """
    user_query: str = Field(
        ...,
        description="The traveler's original emergency, advisory, or tourist question."
    )
    retrieved_context: str = Field(
        ...,
        description="Concatenated context chunks or documents retrieved from the vector database (EmergencyDB / TouristRAG)."
    )
    candidate_response: str = Field(
        ...,
        description="Draft answer generated by the Help Agent that must be verified before user delivery."
    )
    domain: HelpDomain = Field(
        default="general",
        description="The sub-domain of the inquiry ('emergency', 'advisories', 'visa', 'transit', 'general')."
    )


class VerificationResult(BaseModel):
    """
    Structured output schema for the LLM Help Verification Guardrail.
    Enforces hallucination detection, grounding validation, and safe fallback replacement.
    """
    is_grounded: bool = Field(
        ...,
        description="True if every factual claim in the candidate_response is directly supported by the retrieved_context."
    )
    has_hallucination: bool = Field(
        ...,
        description="True if the candidate_response fabricates facts, numbers, dates, fees, or advice not present in the context."
    )
    critical_entities_valid: bool = Field(
        ...,
        description=(
            "True if critical entities (such as emergency dial numbers, fee amounts, and entry requirements) "
            "match official Egyptian records and the retrieved context exactly."
        )
    )
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score of the verification decision between 0.0 (uncertain) and 1.0 (certain)."
    )
    hallucination_details: List[str] = Field(
        default_factory=list,
        description="List of specific hallucinations, unsupported claims, or invalid numbers identified, if any."
    )
    reasoning: str = Field(
        ...,
        description="Concise rationale explaining the evaluation and grounding assessment."
    )
    safe_response: str = Field(
        ...,
        description=(
            "The verified, approved response to return to the user. "
            "If verified (is_grounded=True and has_hallucination=False), this matches candidate_response. "
            "If rejected, this is a clean, deterministic fallback response containing only verified contacts/guidance."
        )
    )

